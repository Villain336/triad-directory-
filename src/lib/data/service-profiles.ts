/**
 * Enriched service/category profiles used by the composition layer and FAQ generator.
 *
 * These capture the NC-specific facts (licensing authority, typical cost ranges,
 * seasonality, related services) that let programmatic city + service pages
 * satisfy the "Page Quality Bar" and "Anti-Duplication System" in the NCSB
 * SEO/GEO Strategy §4.1 and §4.3.
 *
 * Categories not in this file fall back to {@link defaultServiceProfile}.
 */
export interface ServiceProfile {
  slug: string;
  /** Singular form for variable copy ("a plumber", "a licensed electrician"). */
  nameSingular: string;
  /** True if NC state licensing is legally required for this trade. */
  ncLicenseRequired: boolean;
  /** Plain-English name of the NC licensing / regulatory body. */
  ncLicenseAuthority: string;
  /** Public URL for the licensing body. */
  licenseUrl: string;
  /** Low-end typical job cost in NC (USD). */
  averageCostLow: number;
  /** Middle-of-distribution typical job cost in NC (USD). */
  averageCostTypical: number;
  /** High-end typical job cost in NC (USD). */
  averageCostHigh: number;
  /** Human unit for the cost ("per visit", "per project", "per room"). */
  costUnit: string;
  /** 3–6 common jobs homeowners hire this service for. */
  commonJobs: string[];
  /** How often the service is hired in an emergency, on a 3-tier scale. */
  emergencyDemand: "low" | "medium" | "high";
  /** Best time of year to schedule this service in NC. */
  bestSeason: string;
  /** Related service slugs (from src/lib/data/categories.ts) for horizontal linking. */
  relatedServices: string[];
  /**
   * Short definition of the trade, ideally one full sentence, for the
   * `<dl>`-based "definition pattern" LLMs lift heavily (§8.5).
   */
  definition: string;
}

