export function getServiceProfile(slug: string, name: string): ServiceProfile {
  const profile = serviceProfiles[slug];
  if (profile) return profile;
  // derive a singular from the plural name ("Plumbers" -> "Plumber")
  const singular = name.endsWith("s") && !name.endsWith("ss") ? name.slice(0, -1).toLowerCase() : name.toLowerCase();
  return { slug, nameSingular: singular, ...defaultServiceProfile };
}
